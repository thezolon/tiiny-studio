"""Snapshot the Tiiny's API and check it after a TiinyOS update.

- Fetches the OpenAPI specs the device publishes (system/account service on port 80, knowledge base
  under /kb), saves them in docs/api/, and regenerates the endpoint tables in docs/api/*.md.
- Compares with the previous snapshot and lists added, removed and changed endpoints.
- Probes a list of read-only endpoints that aren't in any spec (models, inference, music, 3D, OCR,
  Ollama/Anthropic routes, discovery) and reports their status codes.
Only GET requests are sent, and never to anything that changes the device.

Usage: python tools/api_snapshot.py [--check]     (--check: compare and probe, don't overwrite)
Device address and key: TIINY_URL / TIINY_KEY, else the studio's data/config.json or the desktop app's config
(active device), else ~/.local/tiiny/config.json (TiinyOS)."""
import json
import os
import sys
import urllib.error
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "api"
SPECS = {"gateway": "/openapi.json", "kb": "/kb/openapi.json"}
# Read-only endpoints outside the specs (served by the model service behind port 80, or other ports).
PROBES = [
    "/v1/models", "/api/v1/models/?including_downloading=false", "/api/v1/models/running", "/api/v1/models/types",
    "/api/v1/models/storage", "/api/v1/models/online_models", "/api/v1/model-stats", "/api/v1/npu/status",
    "/api/v1/sys/status", "/api/v1/sys/device_info", "/api/v1/sys/ac_power/", "/api/v1/sys/storage", "/api/v1/sys/wifi/connection_status",
    "/api/services", "/v1/music/info", "/v1/music/sessions", "/v1/3d/capabilities", "/api/tags", "/kb/sources?limit=1",
    ":39218/device.json", ":9109/metrics",
]


def app_config():
    """The desktop app's settings: the per-user folder server.py's user_data_dir() names."""
    if sys.platform == "win32":
        return Path(os.environ.get("APPDATA") or Path.home() / "AppData" / "Roaming") / "Tiiny Studio" / "config.json"
    if sys.platform == "darwin":
        return Path.home() / "Library" / "Application Support" / "Tiiny Studio" / "config.json"
    return Path(os.environ.get("XDG_DATA_HOME") or Path.home() / ".local" / "share") / "tiiny-studio" / "config.json"


def device():
    url, key = os.environ.get("TIINY_URL"), os.environ.get("TIINY_KEY")
    for saved in [] if url else [ROOT / "data" / "config.json", app_config()]:  # a source checkout, then the desktop app
        try:
            c = json.loads(saved.read_text("utf-8"))
            d = next((d for d in c.get("devices", []) if d.get("id") == c.get("active")), (c.get("devices") or [{}])[0])
            url, key = d.get("url"), key or d.get("key")
            break
        except (OSError, ValueError, StopIteration):
            pass
    if not url or not key:
        c = json.loads((Path.home() / ".local" / "tiiny" / "config.json").read_text("utf-8"))
        url = url or "http://" + c["deviceAddress"]
        key = key or c["account"]["authKey"]
    return url.rstrip("/"), key


def get(base, key, path, timeout=8):
    host = base.split("://", 1)[1].split("/")[0].split(":")[0]
    url = f"http://{host}{path}" if path.startswith(":") else base + path
    req = urllib.request.Request(url, headers={"Authorization": f"Bearer {key}", "Accept": "application/json"})
    try:
        with urllib.request.urlopen(req, timeout=timeout) as r:
            return r.status, r.read()
    except urllib.error.HTTPError as e:
        return e.code, e.read()
    except (urllib.error.URLError, OSError) as e:
        return None, str(e).encode()


def ops(spec):
    """{"GET /path": summary} for every operation in a spec."""
    return {f"{m.upper()} {p}": (op.get("summary") or op.get("operationId") or "") for p, item in spec.get("paths", {}).items()
            for m, op in item.items() if m in ("get", "post", "put", "patch", "delete")}


def body_fields(spec, op):
    """Short 'field: type' list for a request body (resolving one $ref level)."""
    content = (op.get("requestBody") or {}).get("content", {})
    schema = next(iter(content.values()), {}).get("schema", {}) if content else {}
    if "$ref" in schema:
        schema = spec.get("components", {}).get("schemas", {}).get(schema["$ref"].split("/")[-1], {})
    props = schema.get("properties", {})
    req = set(schema.get("required", []))
    return ", ".join(f"`{k}`{'*' if k in req else ''}" for k in props) or ("multipart" if "multipart/form-data" in content else "")


def params(op):
    return ", ".join(f"`{p['name']}`{'*' if p.get('required') else ''}" for p in op.get("parameters", []) if p.get("in") in ("query", "path"))


def render(name, spec):
    info = spec.get("info", {})
    lines = [f"# {info.get('title', name)} (generated)", "",
             f"Generated by `tools/api_snapshot.py` from the device's own OpenAPI spec (`{SPECS[name]}`, version "
             f"{info.get('version', '?')}). `*` = required. Full schemas: [`{name}-openapi.json`]({name}-openapi.json).", "",
             "| method | path | what | parameters | body |", "|---|---|---|---|---|"]
    for p, item in spec.get("paths", {}).items():
        for m, op in item.items():
            if m in ("get", "post", "put", "patch", "delete"):
                lines.append(f"| {m.upper()} | `{p}` | {op.get('summary') or ''} | {params(op)} | {body_fields(spec, op)} |")
    return "\n".join(lines) + "\n"


def main():
    check = "--check" in sys.argv
    base, key = device()
    print(f"device: {base}")
    OUT.mkdir(parents=True, exist_ok=True)
    for name, path in SPECS.items():
        code, raw = get(base, key, path)
        if code != 200:
            print(f"{name}: couldn't fetch {path} ({code})"); continue
        spec = json.loads(raw)
        old_path = OUT / f"{name}-openapi.json"
        old = json.loads(old_path.read_text("utf-8")) if old_path.exists() else {}
        new_ops, old_ops = ops(spec), ops(old)
        added = sorted(set(new_ops) - set(old_ops))
        removed = sorted(set(old_ops) - set(new_ops))
        changed = sorted(k for k in set(new_ops) & set(old_ops)
                         if json.dumps(spec["paths"][k.split(" ", 1)[1]][k.split(" ", 1)[0].lower()], sort_keys=True)
                         != json.dumps(old["paths"][k.split(" ", 1)[1]][k.split(" ", 1)[0].lower()], sort_keys=True))
        print(f"{name}: {spec.get('info', {}).get('title')} v{spec.get('info', {}).get('version')}, {len(new_ops)} endpoints"
              f" (was v{old.get('info', {}).get('version', '-')}, {len(old_ops)})")
        for label, items in (("added", added), ("removed", removed), ("changed", changed)):
            for k in items:
                print(f"  {label:8} {k}")
        if not check:
            old_path.write_text(json.dumps(spec, indent=1, ensure_ascii=False), "utf-8")
            (OUT / f"{name}.md").write_text(render(name, spec), "utf-8")
    print("\nendpoints outside the specs (GET only):")
    for path in PROBES:
        code, raw = get(base, key, path, timeout=5)
        note = ""
        if code and code >= 400:
            try:
                e = json.loads(raw)
                note = str((e.get("error") or {}).get("message") if isinstance(e.get("error"), dict) else e.get("detail") or e.get("error"))[:70]
            except ValueError:
                note = raw[:60].decode("utf-8", "replace")
        print(f"  {str(code or 'down'):5} {path} {note}")


if __name__ == "__main__":
    main()
